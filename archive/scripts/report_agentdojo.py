"""Render the AgentDojo grant-defense results into one Markdown table set."""
from __future__ import annotations

import argparse
from collections import defaultdict
import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARM_ORDER = ["none", "repeat_user_prompt", "spotlighting_with_delimiting", "grant_broker", "grant_broker-narrow",
             "grant_broker-v2", "effect_journal", "effect_journal-v2", "grant_advice", "grant_advice-v2"]


def journal_sum(block, key):
    return sum(j.get(key, 0) for j in ((block or {}).get("journal") or {}).values())


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--runs", type=Path, default=ROOT / "runs")
    p.add_argument("--output", type=Path, default=ROOT / "docs/agentdojo-results.md")
    args = p.parse_args()
    rows = []
    for path in sorted(glob.glob(str(args.runs / "agentdojo-*/summaries/*.json"))):
        if "smoke" in path:
            continue
        d = json.loads(Path(path).read_text())
        arm = d["pipeline"].replace(d["model"] + "-", "")
        a, b = d.get("attacked") or {}, d.get("benign") or {}
        rows.append({"model": d["model"], "suite": d["suite"], "attack": d["attack"], "arm": arm, "status": d["status"],
                     "benign_u": b.get("utility"), "benign_n": b.get("n"), "att_u": a.get("utility"), "att_n": a.get("n"),
                     "asr": a.get("attack_success"), "blocked": journal_sum(a, "blocked") + journal_sum(b, "blocked"),
                     "offgrant": journal_sum(a, "unauthorized_executed") + journal_sum(b, "unauthorized_executed"),
                     "asks": journal_sum(a, "requests") + journal_sum(b, "requests"), "requests": d["usage"].get("requests")})
    lines = ["# AgentDojo results (grant defenses versus published baselines)", "",
             "Generated by `scripts/report_agentdojo.py` from `runs/agentdojo-*/summaries/`. Benchmark v1.2.2, agentdojo 0.1.35, "
             "Anthropic SDK 0.125. Benign utility = user tasks passed with no injection. Attacked utility and ASR = over every "
             "user task x injection task pair. Blocked = calls the grant broker refused; off-grant = executed calls outside the "
             "grant in the non-blocking arms; asks = calls to the authorization-request tool. Security comes from AgentDojo's own "
             "scorer. Incomplete arms (budget_stop, error) report only the cases that finished.", ""]
    for attack in sorted({r["attack"] for r in rows}):
        for model in sorted({r["model"] for r in rows}):
            group = [r for r in rows if r["attack"] == attack and r["model"] == model]
            if not group:
                continue
            lines += [f"## {model}, attack `{attack}`", "",
                      "| Suite | Arm | Status | Benign utility | Attacked utility | ASR | Blocked | Off-grant executed | Asks | Requests |",
                      "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
            pooled = defaultdict(lambda: {"bu": 0, "bn": 0, "au": 0, "an": 0, "asr": 0, "blocked": 0, "offgrant": 0, "asks": 0})
            for r in sorted(group, key=lambda r: (r["suite"], ARM_ORDER.index(r["arm"]) if r["arm"] in ARM_ORDER else 99)):
                f = lambda u, n: "–" if u is None or not n else f"{u}/{n} ({100 * u / n:.0f}%)"
                lines.append(f"| {r['suite']} | {r['arm']} | {r['status']} | {f(r['benign_u'], r['benign_n'])} | {f(r['att_u'], r['att_n'])} | "
                             f"{f(r['asr'], r['att_n'])} | {r['blocked']} | {r['offgrant']} | {r['asks']} | {r['requests'] or '–'} |")
                pl = pooled[r["arm"]]
                pl["bu"] += r["benign_u"] or 0; pl["bn"] += r["benign_n"] or 0
                pl["au"] += r["att_u"] or 0; pl["an"] += r["att_n"] or 0; pl["asr"] += r["asr"] or 0
                for k in ("blocked", "offgrant", "asks"):
                    pl[k] += r[k]
            lines += ["", "Pooled over the suites above (finished cases only):", "",
                      "| Arm | Benign utility | Attacked utility | ASR | Blocked | Off-grant executed | Asks |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
            for arm in sorted(pooled, key=lambda a: ARM_ORDER.index(a) if a in ARM_ORDER else 99):
                pl = pooled[arm]
                f = lambda u, n: "–" if not n else f"{u}/{n} ({100 * u / n:.0f}%)"
                lines.append(f"| {arm} | {f(pl['bu'], pl['bn'])} | {f(pl['au'], pl['an'])} | {f(pl['asr'], pl['an'])} | {pl['blocked']} | {pl['offgrant']} | {pl['asks']} |")
            lines.append("")
    lines += ["## Reading", "",
              "- Progent's anchors on the same benchmark: gpt-4o 39.9% -> 1.0% ASR; claude-sonnet-4 6.8% -> 0.5%.",
              "- Both Claude models here sit at or near 0% ASR with no defense, so the benchmark cannot rank the defenses on security for them; the informative column is utility.",
              "- The static grant broker (v1) loses utility through grant omissions, mostly read-only tools. Grant v2 always permits read-only tools and constrains only effectful ones.",
              "- Two Sonnet 4.6 workspace arms ended early (API timeouts after retries; one spending ceiling); their rows cover finished cases only.", ""]
    args.output.write_text("\n".join(lines))
    print(f"wrote {args.output} with {len(rows)} arm rows")


if __name__ == "__main__":
    main()
