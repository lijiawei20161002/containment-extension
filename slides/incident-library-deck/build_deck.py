def text(s, x, y, w, h, content, size=18, color=INK, **kwargs):
    return textbox(s, Inches(x), Inches(y), Inches(w), Inches(h), content, size, color, **kwargs)


def box(s, x, y, w, h, fill=BLUE_PALE, line=None):
    return rect(s, Inches(x), Inches(y), Inches(w), Inches(h), fill, line)


def slide(title, subtitle, stage):
    s = prs.slides.add_slide(BLANK)
    text(s, .5, .18, 11.8, .25, stage.upper(), 10, BLUE, bold=True)
    text(s, .5, .59, 12.3, .64, title, 28, INK, bold=True)
